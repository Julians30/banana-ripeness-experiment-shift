#!/usr/bin/env python3
"""Normalize the reviewer-facing analysis representation.

This utility has two deterministic jobs:

1. During the one-time repository migration, reconstruct the frozen source-clean
   notebooks from the historical ``notebooks_packed/*.ipynb.b85gz`` files.
2. Regenerate one readable ``scripts/<notebook>.py`` mirror per authoritative
   notebook by extracting code cells verbatim, while commenting notebook-only
   shell/magic lines so the mirror remains valid Python syntax.

The scientific notebooks are authoritative. This utility never changes notebook
analysis code, parameters, results, or frozen evidence.
"""
from __future__ import annotations

import base64
import gzip
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK_DIR = ROOT / "notebooks"
PACKED_DIR = ROOT / "notebooks_packed"
SCRIPT_DIR = ROOT / "scripts"

NOTEBOOKS = [
    "01_DATA_AUDIT_AND_FROZEN_LOEO.ipynb",
    "02_PCA_UMAP_DOMAIN_SHIFT.ipynb",
    "03_INNER_LOEO_MODEL_SELECTION.ipynb",
    "04_OUTER_LOEO_EVALUATION.ipynb",
    "05_BALANCING_SENSITIVITY_CLASSWEIGHT_SMOTE.ipynb",
    "06_CALIBRATION_RELIABILITY_ORDINAL.ipynb",
    "06_v1_1_CALIBRATION_WIDE_TEMPERATURE.ipynb",
    "07_FINAL_STATISTICAL_INFERENCE.ipynb",
    "08_FINAL_MANUSCRIPT_TABLES_FIGURES.ipynb",
]

EXPECTED_SOURCE = {
    "01_DATA_AUDIT_AND_FROZEN_LOEO.ipynb": ("02356fe8a51e6ae61b93b5289f1becbdbd99021418922a287a8df2a6776c75a8", 9170),
    "02_PCA_UMAP_DOMAIN_SHIFT.ipynb": ("4c18bdc8ed0cf39afc474e72f1237a4017bb4996bb3811bcd3cf916db7240f9c", 36504),
    "03_INNER_LOEO_MODEL_SELECTION.ipynb": ("7b11ba55fd472c8955a1d8b3077d2a653810b5f27ffc54f98d6735fd5f86c5fe", 31265),
    "04_OUTER_LOEO_EVALUATION.ipynb": ("29e3bcb96a4dfae3c5749f1c3e3988caf57fd7f3bee4f3bd447e3d53478c4d4e", 29995),
    "05_BALANCING_SENSITIVITY_CLASSWEIGHT_SMOTE.ipynb": ("20c7b95995c417fc4e00f35af11fc3a11baf6cea0c127fbbee5cc6a6702383f9", 40388),
    "06_CALIBRATION_RELIABILITY_ORDINAL.ipynb": ("21cc97bac89b13a910e5a7a4009de0a5713ed3b7364239db678edfac32484eca", 42401),
    "06_v1_1_CALIBRATION_WIDE_TEMPERATURE.ipynb": ("d8999076c4c067be8aba6a83f3ad2b5351c784ac7646f879c1055aa024f496bd", 33826),
    "07_FINAL_STATISTICAL_INFERENCE.ipynb": ("3232477307baea128472ecd12fee0346168a548cf6b117a99ca7f8e1878b674b", 35257),
    "08_FINAL_MANUSCRIPT_TABLES_FIGURES.ipynb": ("8efd3456de3bf2ee2eb6c78a2a60721c582937232b1fe8e2b8363e5a601f32d3", 47560),
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def restore_missing_notebooks() -> None:
    NOTEBOOK_DIR.mkdir(exist_ok=True)
    for name in NOTEBOOKS:
        direct = NOTEBOOK_DIR / name
        if direct.exists():
            continue
        packed = PACKED_DIR / f"{name}.b85gz"
        if not packed.exists():
            raise SystemExit(f"Missing authoritative notebook and packed migration source: {name}")
        data = gzip.decompress(base64.b85decode(packed.read_bytes()))
        direct.write_bytes(data)
        print(f"Restored {direct.relative_to(ROOT)}")


def verify_frozen_notebooks() -> None:
    for name in NOTEBOOKS:
        path = NOTEBOOK_DIR / name
        if not path.exists():
            raise SystemExit(f"Missing notebook: {name}")
        data = path.read_bytes()
        expected_hash, expected_bytes = EXPECTED_SOURCE[name]
        got_hash = sha256(data)
        if got_hash != expected_hash or len(data) != expected_bytes:
            raise SystemExit(
                f"Frozen notebook mismatch for {name}: "
                f"sha256={got_hash}, bytes={len(data)}; "
                f"expected sha256={expected_hash}, bytes={expected_bytes}"
            )
        json.loads(data.decode("utf-8"))
    print(f"Verified {len(NOTEBOOKS)} frozen source-clean notebooks byte-for-byte.")


def notebook_to_script(name: str) -> str:
    nb = json.loads((NOTEBOOK_DIR / name).read_text(encoding="utf-8"))
    out = [
        "#!/usr/bin/env python3\n",
        '"""Auto-generated readable mirror of the authoritative Jupyter notebook.\n\n',
        f"Source: notebooks/{name}\n",
        "The notebook is the canonical execution record. This mirror is generated\n",
        "deterministically for code review and text-based diffing. Notebook-only\n",
        "shell/magic lines are commented, but all other code-cell text is retained.\n",
        'Do not edit this file manually; run scripts/rebuild_analysis_mirrors.py.\n"""\n\n',
    ]
    code_number = 0
    for cell_index, cell in enumerate(nb.get("cells", [])):
        if cell.get("cell_type") != "code":
            continue
        code_number += 1
        src = cell.get("source", "")
        if isinstance(src, list):
            src = "".join(src)
        out.append(f"\n# %% [code cell {code_number}; notebook cell index {cell_index}]\n")
        if not src.endswith("\n"):
            src += "\n"
        for line in src.splitlines(keepends=True):
            stripped = line.lstrip()
            if stripped.startswith(("!", "%")):
                indent = line[: len(line) - len(stripped)]
                newline = "\n" if line.endswith("\n") else ""
                body = stripped[:-1] if newline else stripped
                out.append(f"{indent}# NOTEBOOK_ONLY: {body}{newline}")
            else:
                out.append(line)
    return "".join(out)


def rebuild_script_mirrors() -> None:
    SCRIPT_DIR.mkdir(exist_ok=True)
    for name in NOTEBOOKS:
        script_name = name.removesuffix(".ipynb") + ".py"
        text = notebook_to_script(name)
        path = SCRIPT_DIR / script_name
        path.write_text(text, encoding="utf-8", newline="\n")
        compile(text, str(path), "exec")
        print(f"Wrote {path.relative_to(ROOT)}")


def remove_historical_packing_layer() -> None:
    old_unpack = SCRIPT_DIR / "unpack_notebooks.py"
    if old_unpack.exists():
        old_unpack.unlink()
        print("Removed scripts/unpack_notebooks.py")
    if PACKED_DIR.exists():
        shutil.rmtree(PACKED_DIR)
        print("Removed notebooks_packed/")


def main() -> None:
    restore_missing_notebooks()
    verify_frozen_notebooks()
    rebuild_script_mirrors()
    remove_historical_packing_layer()
    print("Repository analysis representation is normalized.")


if __name__ == "__main__":
    main()
