#!/usr/bin/env python3
"""Materialize frozen notebooks and readable Python mirrors for local review.

This utility is intentionally NOT run by CI. It reconstructs NB02–NB08 from the
immutable provenance payloads under archive/frozen_notebook_payloads/, verifies
all nine frozen notebook SHA-256 values, and writes readable .py mirrors.

It never changes model logic, parameters, predictions, tables, or scientific
results. Generated notebooks/scripts can be deleted and regenerated at any time.
"""
from __future__ import annotations

import base64
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK_DIR = ROOT / "notebooks"
ARCHIVE_DIR = ROOT / "archive" / "frozen_notebook_payloads"
SCRIPT_DIR = ROOT / "scripts"

NOTEBOOKS = [
    "01_DATA_AUDIT_AND_FROZEN_LOEO.ipynb",
    "02_PCA_UMAP_DOMAIN_SHIFT.ipynb",
    "03_INNER_LOEO_MODEL_SELECTION.ipynb",
    "04_OUTER_LOEO_EVALUATION.ipynb",
    "05_BALANCING_SENSITIVITY_CLASSWEIGHT_SMOTE.ipynb",
    "06_CALIBRATION_RELIABILITY_ORDINAL.ipynb",
    "06_v1_1_CALIBRATION_WIDE_TEMPERATURE.ipynb",
    "07_FINAL_STATISTICAL_INFERENCE.ipynb",
    "08_FINAL_MANUSCRIPT_TABLES_FIGURES.ipynb",
]

EXPECTED_SOURCE = {
    "01_DATA_AUDIT_AND_FROZEN_LOEO.ipynb": ("02356fe8a51e6ae61b93b5289f1becbdbd99021418922a287a8df2a6776c75a8", 9170),
    "02_PCA_UMAP_DOMAIN_SHIFT.ipynb": ("4c18bdc8ed0cf39afc474e72f1237a4017bb4996bb3811bcd3cf916db7240f9c", 36504),
    "03_INNER_LOEO_MODEL_SELECTION.ipynb": ("7b11ba55fd472c8955a1d8b3077d2a653810b5f27ffc54f98d6735fd5f86c5fe", 31265),
    "04_OUTER_LOEO_EVALUATION.ipynb": ("29e3bcb96a4dfae3c5749f1c3e3988caf57fd7f3bee4f3bd447e3d53478c4d4e", 29995),
    "05_BALANCING_SENSITIVITY_CLASSWEIGHT_SMOTE.ipynb": ("20c7b95995c417fc4e00f35af11fc3a11baf6cea0c127fbbee5cc6a6702383f9", 40388),
    "06_CALIBRATION_RELIABILITY_ORDINAL.ipynb": ("21cc97bac89b13a910e5a7a4009de0a5713ed3b7364239db678edfac32484eca", 42401),
    "06_v1_1_CALIBRATION_WIDE_TEMPERATURE.ipynb": ("d8999076c4c067be8aba6a83f3ad2b5351c784ac7646f879c1055aa024f496bd", 33826),
    "07_FINAL_STATISTICAL_INFERENCE.ipynb": ("3232477307baea128472ecd12fee0346168a548cf6b117a99ca7f8e1878b674b", 35257),
    "08_FINAL_MANUSCRIPT_TABLES_FIGURES.ipynb": ("59b4f7e2dcc6cfb214536cf31736b50a2af9666b207387eb897ff6f994d58c9e", 46883),
}

def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def verify(name: str, data: bytes) -> None:
    expected_hash, expected_size = EXPECTED_SOURCE[name]
    if len(data) != expected_size or sha256(data) != expected_hash:
        raise SystemExit(
            f"Frozen notebook mismatch for {name}: "
            f"sha256={sha256(data)}, bytes={len(data)}; "
            f"expected sha256={expected_hash}, bytes={expected_size}"
        )
    json.loads(data.decode("utf-8"))

def materialize_notebooks() -> None:
    NOTEBOOK_DIR.mkdir(exist_ok=True)
    first = NOTEBOOK_DIR / NOTEBOOKS[0]
    if not first.exists():
        raise SystemExit(f"Missing canonical NB01: {first}")
    verify(NOTEBOOKS[0], first.read_bytes())

    for name in NOTEBOOKS[1:]:
        payload = ARCHIVE_DIR / f"{name}.b85gz"
        if not payload.exists():
            raise SystemExit(f"Missing provenance payload: {payload}")
        data = gzip.decompress(base64.b85decode(payload.read_bytes()))
        verify(name, data)
        target = NOTEBOOK_DIR / name
        target.write_bytes(data)
        print(f"Materialized {target.relative_to(ROOT)}")
    print("Verified all nine frozen notebook sources.")

def notebook_to_script(name: str) -> str:
    nb = json.loads((NOTEBOOK_DIR / name).read_text(encoding="utf-8"))
    out = [
        "#!/usr/bin/env python3\n",
        '"""Auto-generated readable mirror of the authoritative Jupyter notebook.\n\n',
        f"Source: notebooks/{name}\n",
        "The notebook is the canonical execution record. This mirror is generated\n",
        "deterministically for code review and text-based diffing. Notebook-only\n",
        "shell/magic lines are commented, but all other code-cell text is retained.\n",
        'Do not edit this file manually; run scripts/rebuild_analysis_mirrors.py.\n"""\n\n',
    ]
    code_number = 0
    for cell_index, cell in enumerate(nb.get("cells", [])):
        if cell.get("cell_type") != "code":
            continue
        code_number += 1
        src = cell.get("source", "")
        if isinstance(src, list):
            src = "".join(src)
        out.append(f"\n# %% [code cell {code_number}; notebook cell index {cell_index}]\n")
        if not src.endswith("\n"):
            src += "\n"
        for line in src.splitlines(keepends=True):
            stripped = line.lstrip()
            if stripped.startswith(("!", "%")):
                indent = line[: len(line) - len(stripped)]
                newline = "\n" if line.endswith("\n") else ""
                body = stripped[:-1] if newline else stripped
                out.append(f"{indent}# NOTEBOOK_ONLY: {body}{newline}")
            else:
                out.append(line)
    return "".join(out)

def rebuild_scripts() -> None:
    SCRIPT_DIR.mkdir(exist_ok=True)
    for name in NOTEBOOKS:
        script_name = name.removesuffix(".ipynb") + ".py"
        text = notebook_to_script(name)
        compile(text, script_name, "exec")
        path = SCRIPT_DIR / script_name
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(ROOT)}")

def main() -> None:
    materialize_notebooks()
    rebuild_scripts()
    print("Local reviewer-facing analysis materialization completed successfully.")

if __name__ == "__main__":
    main()
